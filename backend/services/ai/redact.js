// ปิดข้อมูลที่ระบุตัวบุคคลได้ ก่อนส่งข้อความไปบริการ AI ภายนอก (ไม่ใช่การรับประกันเต็มร้อย แต่ลดความเสี่ยงของเลขยาวที่หลุดไป)
// จำนวนเงินปกติ (เช่น 65, 1,250, 12000) ไม่โดนปิด เพราะสั้นกว่า 9 หลัก
const RULES = [
  [/[\w.+-]+@[\w-]+(?:\.[\w-]+)+/g, '[อีเมล]'],
  [/(?<![\d])\d[ -]?\d{4}[ -]?\d{5}[ -]?\d{2}[ -]?\d(?![\d])/g, '[เลขบัตรประชาชน]'], // 13 หลัก (x-xxxx-xxxxx-xx-x)
  [/(?<![\d])(?:\d[ -]?){13,19}(?![\d])/g, '[เลขบัตร]'],
  [/(?<![\d])0[689]\d[ -]?\d{3}[ -]?\d{4}(?![\d])/g, '[เบอร์โทร]'], // มือถือ
  [/(?<![\d])0\d[ -]?\d{3}[ -]?\d{4}(?![\d])/g, '[เบอร์โทร]'], // เบอร์บ้าน (02-xxx-xxxx)
  [/(?<![\d])\d{3}[ -]?\d[ -]?\d{5}[ -]?\d(?![\d])/g, '[เลขบัญชี]'], // xxx-x-xxxxx-x
  [/(?<![\d])\d{9,}(?![\d])/g, '[เลขยาว]'],
];

function redactSensitive(input) {
  let text = String(input === undefined || input === null ? '' : input);
  let count = 0;
  for (const [re, label] of RULES) {
    text = text.replace(re, () => { count += 1; return label; });
  }
  return { text, count };
}

module.exports = { redactSensitive };
